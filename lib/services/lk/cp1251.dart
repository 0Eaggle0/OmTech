/// Декодер windows-1251 → unicode без внешних пакетов.
///
/// На /ecab/ страницах Bitrix ставит `<meta charset="windows-1251">`,
/// сервер отдаёт байты в этой однобайтовой кодировке, а dart:convert
/// «из коробки» этого не умеет. Делаем lookup-таблицу: байт → codepoint.
String decodeCp1251(List<int> bytes) {
  final buf = StringBuffer();
  for (final b in bytes) {
    buf.writeCharCode(_cp1251[b & 0xFF]);
  }
  return buf.toString();
}

